"""JS spawner == committed reference vectors (spec/portability.md 7.1), executed in Chromium on the served module."""

from __future__ import annotations

import hashlib
import json

import pytest
from gameplay_harness import GAMEPLAY_PATH, ROOT, gameplay, harness_browser, harness_url, hpage  # noqa: F401

VEC_DIR = ROOT / "tests" / "fixtures" / "portability"

RUN_JS = """
async ({cases, loops}) => {
  const { generateLoop } = await import('/js/game/spawner.js');
  const gp = await (await fetch('/api/gameplay.json')).json();
  const out = {};
  for (const c of cases) {
    const rows = [];
    for (const L of loops) rows.push(...generateLoop(gp, c.input, L));
    out[c.name] = rows;
  }
  return out;
}
"""


def _load(name: str) -> dict:
    path = VEC_DIR / name
    assert path.exists(), f"missing committed vector file {path} (generated by hero.tools.make_spawner_vectors)"
    return json.loads(path.read_text())


@pytest.mark.parametrize("fname,min_cases", [("spawner_vectors.json", 8), ("spawner_vectors_bulk.json", 100)])
def test_js_spawner_equals_reference_vectors(hpage, fname, min_cases):  # noqa: F811
    vec = _load(fname)
    assert vec["schema"] == "hero-spawner-vectors/1"
    assert len(vec["cases"]) >= min_cases
    loops = list(range(vec.get("loops", 3)))
    got = hpage.evaluate(RUN_JS, {"cases": vec["cases"], "loops": loops})
    bad = [c["name"] for c in vec["cases"] if got[c["name"]] != c["expected"]]
    assert not bad, f"JS spawner diverges from the vectors in {len(bad)} case(s): {bad[:5]}"
    assert any(c["expected"] for c in vec["cases"]), "vectors would be vacuous: every case is empty"
    assert not hpage.hero_errors


def test_vectors_are_keyed_to_the_current_gameplay_json():
    """Changing gameplay.json invalidates the committed vectors (they must be regenerated)."""
    sha = hashlib.sha256(GAMEPLAY_PATH.read_bytes()).hexdigest()
    for fname in ("spawner_vectors.json", "spawner_vectors_bulk.json"):
        assert _load(fname)["gameplay_sha256"] == sha, f"{fname} is stale w.r.t. src/hero/export/gameplay.json"


def test_vector_mismatch_is_detected(hpage):  # noqa: F811
    """Error path: the comparison is not vacuous - a perturbed input gives a different list."""
    vec = _load("spawner_vectors.json")
    case = json.loads(json.dumps(vec["cases"][0]))
    case["input"]["seed"] += 1
    got = hpage.evaluate(RUN_JS, {"cases": [case], "loops": list(range(vec.get("loops", 3)))})
    assert got[case["name"]] != vec["cases"][0]["expected"]
